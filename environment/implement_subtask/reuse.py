"""Safely reuse successful Macro reviews from a COMPLETED prior reporting run.

A corrected author/guard implementation changes the code hash, so the
existing journal MUST NOT be resumed in place. Instead --reuse-from reads
and validates the old completed, checkpointed reporting run and carries
forward only accepted, exactly Oracle-grounded rows into a NEW run.

Rejected Macros are not copied: they are regenerated by the current
Author/Critic. This also makes previously withheld, but individually
accepted, Macros usable when their sibling Macro is repaired.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from environment.streaming import SCHEMA, StreamingError, file_digest, stable_signature

from .reporting import PRESENTATION, trace_narrative


def _read_committed(path: Path, end: int, expected_sha256: str) -> list[dict]:
    if not path.is_file() or type(end) is not int or end < 0:
        raise StreamingError("previous_checkpoint_missing_output:" + str(path))
    if path.stat().st_size < end:
        raise StreamingError("previous_checkpoint_truncated_output:" + str(path))
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        data = handle.read(end)
        digest.update(data)
    if digest.hexdigest() != expected_sha256:
        raise StreamingError("previous_checkpoint_hash_mismatch:" + str(path))
    try:
        return [json.loads(x) for x in data.splitlines()]
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise StreamingError("previous_checkpoint_invalid_JSONL:" + str(path)) from exc


def _validate_reused_result(accepted: dict, teacher: dict) -> None:
    """Never inherit a cached message for a different Oracle task."""
    if not isinstance(accepted, dict):
        raise StreamingError("previous_accepted_not_object")
    immutable = (
        "scene_task_id", "macro_task_id", "depends_on",
        "authorized_source_ids", "output_schema", "answer",
        "answer_with_provenance", "grounding",
    )
    if any(accepted.get(field) != teacher.get(field) for field in immutable):
        raise StreamingError(
            "previous_accepted_not_equal_to_current_oracle:"
            + str(teacher["scene_task_id"]) + "::" + str(teacher["macro_task_id"])
        )
    old_trace = accepted.get("trace_summary", {})
    new_trace = teacher.get("trace_summary", {})
    if (not isinstance(old_trace, dict)
            or old_trace.get("steps") != new_trace.get("steps")):
        raise StreamingError("previous_accepted_operator_evidence_changed")
    if any(
        old_trace.get(key) != new_trace.get(key)
        for key in new_trace if key != "narrative"
    ):
        raise StreamingError("previous_accepted_trace_provenance_changed")
    finish = accepted.get("finish_result", {})
    review = accepted.get("report_authoring", {})
    if (not isinstance(finish, dict) or finish.get("status") != "done"
            or not isinstance(finish.get("result"), str)
            or not isinstance(finish.get("summary"), str)
            or not isinstance(review, dict)
            or review.get("status") != "accepted"
            or not review.get("exact_answer_immutable")
            or accepted.get("answer_text") != finish["result"]
            or old_trace.get("narrative") != (
                trace_narrative(new_trace) if review.get("presentation") == PRESENTATION
                else finish["summary"]
            )):
        raise StreamingError("previous_accepted_invalid_finish_contract")
    if teacher.get("evidence_trust_version"):
        from .visible_evidence import witnessed_source_summary
        witness = witnessed_source_summary(teacher)
        if witness and witness not in finish["summary"]:
            raise StreamingError("previous_accepted_missing_public_claim_witness")
    if review.get("result_policy") == "code_owned":
        from .reporting import code_owned_result
        if finish["result"] != code_owned_result(teacher):
            raise StreamingError("reused_code_owned_result_drift")
    critic = review.get("review", {})
    if not isinstance(critic, dict) or critic.get("verdict") != "pass":
        raise StreamingError("previous_accepted_missing_critic_pass")


def load_completed_accepted(folder: Path, ordered: list[tuple]) -> tuple[dict, str]:
    """Return (verified accepted rows indexed by scene::macro, provenance hash).

    Read-only. Requires FULL previous run to have a completed checkpoint, a
    terminal summary, correct ordered audit, and matching immutable Oracle.
    """
    folder = Path(folder).expanduser().resolve()
    state_path = folder / "subagent_reports_progress.json"
    summary_path = folder / "summary.json"
    if not state_path.is_file() or not summary_path.is_file():
        raise StreamingError("previous_run_missing_checkpoint_or_summary")
    try:
        state = json.loads(state_path.read_text(encoding="utf-8"))
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise StreamingError("previous_run_invalid_checkpoint_or_summary") from exc
    expected_ids = [sid + "::" + row["macro_task_id"]
                    for sid, row, _, _ in ordered]
    if (state.get("schema") != SCHEMA
            or state.get("task_ids") != expected_ids
            or state.get("completed") != len(ordered)
            or state.get("accepted", 0) + state.get("rejected", 0)
               != len(ordered)
            or summary.get("status") not in {"done", "partial", "failed"}
            or summary.get("completed_macro_tasks") != len(ordered)
            or summary.get("author_critic_passed_macros") != state["accepted"]
            or summary.get("author_critic_failed_macros") != state["rejected"]):
        raise StreamingError(
            "previous_run_incomplete_or_incompatible_order_and_counts"
        )
    names = {
        key: folder / ("subagent_reports_" + key + ".jsonl")
        for key in ("accepted", "rejected", "audit")
    }
    data = {
        key: _read_committed(
            path, state.get("offsets", {}).get(key),
            state.get("sha256", {}).get(key, ""),
        )
        for key, path in names.items()
    }
    if (len(data["accepted"]) != state["accepted"]
            or len(data["rejected"]) != state["rejected"]
            or len(data["audit"]) != state["completed"]):
        raise StreamingError("previous_run_committed_record_count_mismatch")
    accepted_rows = iter(data["accepted"])
    rejected_rows = iter(data["rejected"])
    reused = {}
    for ix, (entry, expected, task_id) in enumerate(
        zip(data["audit"], ordered, expected_ids)
    ):
        sid, teacher, _, _ = expected
        if (entry.get("index") != ix or entry.get("task_id") != task_id
                or type(entry.get("accepted")) is not bool):
            raise StreamingError("previous_run_audit_order_mismatch")
        record = next(accepted_rows if entry["accepted"] else rejected_rows)
        if record.get("task_id") != task_id:
            raise StreamingError("previous_run_outcome_audit_mismatch")
        if entry["accepted"]:
            cached = record["payload"]
            _validate_reused_result(cached, teacher)
            reused[task_id] = cached
    signature = stable_signature({
        "prior_checkpoint": file_digest(state_path),
        "prior_accepted": file_digest(names["accepted"]),
        "prior_audit": file_digest(names["audit"]),
        "source_path": str(folder),
    })
    return reused, signature
