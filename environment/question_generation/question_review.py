"""Model-facing question writing, targeted critique, and final review.

Only the deterministic, PUBLIC Scoped question and candidate text enter any
LLM call. Neither the hidden World, answer, Gold, ProgramIR, nor private
review history is sent to the final judge.
"""
from __future__ import annotations

import json
import re
from collections.abc import Mapping
from typing import Any

from .contracts import typed_values
from .semantic_checks import (
    validate_group_decisions, check_failures, CheckFormatError,
)


class ReviewFormatError(ValueError):
    """A model response does not satisfy the small review contract."""


_AUTHOR_SYSTEM = """Write a clear, naturally phrased information-seeking question.
The reference is a correct but mechanical question generated by a compiler.
You may combine sentences, use natural pronouns with unambiguous referents
and reorganize phrasing. Do not change the answer being requested.

Preserve EVERY answer-defining clue, condition, comparison, quantifier,
relation direction, owner of each condition, conjunction/disjunction,
search scope, code and date. Do not invent facts or exclude an anchor
unless the reference does. Do not include a solution, answer, task IDs,
program names, artificial group names, or internal instructions.

On a revision, EDIT the previous draft in response to SPECIFIC reviewer
observations, preserving its correct and natural parts. Never discard the
previous draft and simply repeat the reference unless absolutely necessary.
Return valid JSON only: {"question": "<the complete revised question>"}.
"""


_CRITIC_SYSTEM = """You are a constructive question editor. Compare the
public reference to the candidate as a real reader, not as a program parser.
Check whether the SAME answer would be correct under every stated condition.
Critically examine: AND vs OR, filter OWNER, relation subject/object/direction,
intermediate referents, numbers/dates/codes, and answer type.

The input has at most FOUR risk groups (some containing many requirements).
Give ONE status per GROUP: preserved only if ALL listed requirements are
preserved, changed if ANY is changed, uncertain if meaning is ambiguous.
Explain the most decisive discrepancy, not a full report per node.
Each group's requirements have public atomic ids. Report problem_ids=[] for
preserved; for changed/uncertain provide the exact ids whose meaning changed
or cannot be verified. A relation such as "named after" is not equivalent
to sharing the same name. A final ranked selection across TWO alternative
candidate pools uses OR (a result may originate in EITHER pool), even when
one pool itself uses AND (an intermediate intersection). Do not infer that
the final pool is an intersection. Reordering group descriptions does not
change semantics. Never claim an attribute value was omitted without
verifying whether it appears in the actual candidate; if present, assess
its owning entity or relation instead. Do not label a group changed while
explaining that every requirement was preserved.

Choose pass only for equivalent and genuinely more natural text. For revise
return actionable changes to the previous draft, naming the specific lost
condition or changed relationship. Do NOT demand original phrasing or groups.
Return a SHORT JSON object with verdict, issues, summary and checks.
Return every requested group ID exactly once, even when uncertain; missing
check IDs invalidate the entire review.
"""

_FINAL_SYSTEM = """You are an independent final semantic and language judge.
Compare only the correct public reference with the final candidate. You do
not see past Critic votes or revision history.

For each of at most FOUR risk groups, assess ALL its requirements:
intersection vs union, owner of each filter, relation direction/hop,
and final requested answer. Treat any changed or uncertain requirement
as a reason NOT to pass. For each check provide problem_ids:
[] when preserved; otherwise the ids of specific altered/ambiguous public
requirements. A negative group without a concrete problematic requirement
is not justified. Do not label changed while explaining all requirements
are preserved. Do not rubber-stamp a fluent paraphrase. In particular, a group described as a union when the reference demands an
intersection changes the answer; so does transferring a population/date
filter from the answer entity to a related place.

Assess naturalness independently. Minor word replacements, copied group
boilerplate, or a generic preamble around an unchanged reference do not
count as improvement. Natural equivalents can reorder and merge clauses.
Return a SHORT JSON object with verdict, semantic_equivalence,
naturalness, issues, explanation and checks. Return each requested
risk group ID exactly once, including groups you are uncertain about.
"""

_ISSUE_SCHEMA = {
    "type": "object",
    "properties": {
        "kind": {"type": "string"},
        "severity": {"enum": ["major", "minor"]},
        "explanation": {"type": "string"},
        "suggestion": {"type": "string"},
    },
    "required": ["kind", "severity", "explanation", "suggestion"],
    "additionalProperties": False,
}

_CHECK_SCHEMA = {
    "type": "object",
    "properties": {
        "id": {"type": "string"},
        "status": {"enum": ["preserved", "changed", "uncertain"]},
        "explanation": {"type": "string"},
        "problem_ids": {"type": "array", "items": {"type": "string"},
                        "maxItems": 5},
    },
    "required": ["id", "status", "explanation", "problem_ids"],
    "additionalProperties": False,
}
_CRITIC_SCHEMA = {
    "type": "object",
    "properties": {
        "verdict": {"enum": ["pass", "revise", "uncertain"]},
        "issues": {"type": "array", "items": _ISSUE_SCHEMA},
        "summary": {"type": "string"},
        "checks": {"type": "array", "items": _CHECK_SCHEMA},
    },
    "required": ["verdict", "issues", "summary", "checks"],
    "additionalProperties": False,
}
_FINAL_SCHEMA = {
    "type": "object",
    "properties": {
        "verdict": {"enum": ["pass", "reject", "uncertain"]},
        "semantic_equivalence": {"enum": ["equivalent", "different", "uncertain"]},
        "naturalness": {"enum": ["improved", "not_improved", "uncertain"]},
        "issues": {"type": "array", "items": {"type": "string"}},
        "explanation": {"type": "string"},
        "checks": {"type": "array", "items": _CHECK_SCHEMA},
    },
    "required": ["verdict", "semantic_equivalence", "naturalness", "issues",
                 "explanation", "checks"],
    "additionalProperties": False,
}
# Enumerated clauses are not semantic numbers.
_LIST_MARKERS = re.compile(
    r"(?<!\w)\(\s*\d{1,2}\s*\)(?=\s|$)|^\s*\d{1,2}[.)]\s+",
    re.MULTILINE,
)


def literal_warnings(reference: str, candidate: str) -> dict[str, list[str]]:
    """Return advisory-only type-aware differences, never a hard veto.

    A reviewer must still determine whether an apparent difference changes
    meaning. ISO/prose dates, comma-separated numbers and +codes are typed.
    """
    # Natural phrases such as "one of those places" are not numeric
    # predicates. Treat spelled-out numbers as a reviewer issue rather than
    # labelling every ordinary "one/two" as an invented literal here.
    original = typed_values(_LIST_MARKERS.sub(" ", reference), words=False)
    changed = typed_values(_LIST_MARKERS.sub(" ", candidate), words=False)
    def display(values):
        return sorted(f"{kind}:{value}" for kind, value in values)
    return {"possibly_missing": display(original - changed),
            "possibly_added": display(changed - original)}


def _invoke(backend: Any, system: str, data: dict,
            *, schema: Mapping | None = None) -> dict:
    if not callable(getattr(backend, "complete_json", None)):
        raise ReviewFormatError("model_backend_unavailable")
    response = backend.complete_json(
        system, json.dumps(data, ensure_ascii=False),
        response_schema=schema,
    )
    if not isinstance(response, dict):
        raise ReviewFormatError("model_response_not_object")
    return response


def _validate_review_with_diagnostics(groups: list[dict], response: dict) -> None:
    """Explain a missing v16/v17 risk group without logging private data.

    A model may produce syntactically valid JSON yet omit entire groups.
    Report IDs/count/shape, not the candidate or any source/witness text.
    """
    try:
        validate_group_decisions(groups, response.get("checks"))
    except CheckFormatError as exc:
        raw = response.get("checks")
        received_ids = [
            item.get("id") for item in raw
            if isinstance(item, dict) and isinstance(item.get("id"), str)
        ] if isinstance(raw, list) else []
        error = ReviewFormatError(str(exc))
        expected_by_group = {
            group["id"]: {
                requirement["id"] for requirement in group["requirements"]
                if "id" in requirement
            }
            for group in groups
        }
        group_details = []
        for item in raw[:4] if isinstance(raw, list) else ():
            if not isinstance(item, dict):
                group_details.append({"item_type": type(item).__name__})
                continue
            group_id = str(item.get("id", ""))[:24]
            problem_ids = item.get("problem_ids")
            ids = ([str(value)[:40] for value in problem_ids[:8]]
                   if isinstance(problem_ids, list) else None)
            allowed = expected_by_group.get(group_id, set())
            group_details.append({
                "group_id": group_id,
                "status": str(item.get("status", ""))[:20],
                "problem_ids": ids,
                "problem_ids_type": type(problem_ids).__name__,
                "unknown_problem_ids": (
                    [pid for pid in ids if pid not in allowed] if ids else []
                ),
                "allowed_problem_ids": sorted(allowed)[:30],
            })
        error.diagnostic = {
            "expected_group_ids": [g["id"] for g in groups],
            "received_group_ids": received_ids,
            "received_count": len(raw) if isinstance(raw, list) else None,
            "checks_value_type": type(raw).__name__,
            "group_details": group_details,
            "response_keys": sorted(response.keys()),
        }
        raise error from exc


def _guard_unverified_omission_feedback(
    candidate: str, issues: list[dict],
) -> None:
    """Do not send an ungrounded numeric-omission instruction to Author.

    The referenced value can still have a WRONG OWNER. This advisory only
    neutralizes an unsupported claim of literal absence, never approves a
    candidate or erases a failed risk-group judgment.
    """
    present = set(typed_values(candidate, words=False))
    for issue in issues:
        explanation = issue.get("explanation", "")
        if (not re.search(r"\b(?:omitt?ed?|miss(?:es|ing)?|dropped|absent)\b",
                          explanation, re.I)
                or not isinstance(explanation, str)):
            continue
        cited = set(typed_values(explanation, words=False))
        if not cited.intersection(present):
            continue
        issue["explanation"] = (
            "Reviewer claimed that a value was omitted, but a cited numeric "
            "value appears in the candidate. This is an unverified claim: "
            "check whether the value belongs to the SAME entity/relation "
            "as in the reference before editing."
        )
        issue["suggestion"] = (
            "Compare the owning entity and relation path against the public "
            "reference; do not add or remove a numeric condition merely "
            "because the reviewer called it missing."
        )


def author_question(backend: Any, reference: str, *,
                    previous: str | None = None,
                    feedback: dict | None = None) -> str:
    data = {"reference_question": reference}
    if previous is not None:
        data["previous_draft"] = previous
        data["reviewer_feedback"] = feedback or {}
        data["instruction"] = "Revise the PREVIOUS draft using the feedback."
    response = _invoke(backend, _AUTHOR_SYSTEM, data)
    question = response.get("question")
    if not isinstance(question, str):
        raise ReviewFormatError("author_question_missing")
    return " ".join(question.split())


def critique_question(backend: Any, reference: str, candidate: str,
                      checks: list[dict], *, use_schema: bool = True) -> dict:
    payload = {
        "reference_question": reference,
        "candidate_question": candidate,
        "risk_groups": checks,
        "potential_literal_changes_to_check": literal_warnings(reference, candidate),
    }
    if not use_schema:
        # A second chance after a schema/protocol error: pinpoint the missing
        # output obligations, without revealing private answers or rerunning Author.
        payload["required_review_group_ids"] = [g["id"] for g in checks]
        payload["format_repair_instruction"] = (
            "Return exactly one checks entry for EACH required_review_group_id "
            "and no other IDs; status may be uncertain. Return short JSON."
        )
    response = _invoke(
        backend, _CRITIC_SYSTEM, payload,
        schema=_CRITIC_SCHEMA if use_schema else None,
    )
    _validate_review_with_diagnostics(checks, response)
    if response.get("verdict") not in ("pass", "revise", "uncertain"):
        raise ReviewFormatError("critic_verdict_invalid")
    issues = response.get("issues")
    if not isinstance(issues, list) or len(issues) > 8:
        raise ReviewFormatError("critic_issues_invalid")
    for item in issues:
        if (not isinstance(item, dict)
                or item.get("severity") not in ("major", "minor")
                or not all(isinstance(item.get(k), str)
                           for k in ("kind", "explanation", "suggestion"))):
            raise ReviewFormatError("critic_issue_schema_invalid")
    if not isinstance(response.get("summary"), str):
        raise ReviewFormatError("critic_summary_invalid")
    issues = [dict(item) for item in issues]
    failures = [item for item in response["checks"]
                if item["status"] != "preserved"]
    verdict = response["verdict"]
    if failures and verdict == "pass":
        verdict = "revise"
    for item in failures:
        group = next(c for c in checks if c["id"] == item["id"])
        if not any(issue.get("kind") == f"risk_group_{item['id']}"
                   for issue in issues):
            issues.append({
                "kind": f"risk_group_{item['id']}",
                "severity": "major",
                "explanation": item["explanation"],
                "suggestion": (
                    "Repair the " + group["kind"] +
                    " discrepancy; preserve ALL of the group's reference "
                    "requirements with their original owners and relations."
                ),
            })
    _guard_unverified_omission_feedback(candidate, issues)
    return {"verdict": verdict, "issues": issues,
            "summary": response["summary"], "checks": response["checks"]}


def judge_question(backend: Any, reference: str, candidate: str,
                   checks: list[dict], *, use_schema: bool = True) -> dict:
    """Independent reference-and-candidate review, not a ProgramIR parser."""
    payload = {
        "reference_question": reference,
        "candidate_question": candidate,
        "risk_groups": checks,
        "potential_literal_changes_to_check": literal_warnings(reference, candidate),
    }
    if not use_schema:
        payload["required_review_group_ids"] = [g["id"] for g in checks]
        payload["format_repair_instruction"] = (
            "Return one checks entry for EACH required_review_group_id, even "
            "if uncertain. Do not omit or invent IDs."
        )
    response = _invoke(
        backend, _FINAL_SYSTEM, payload,
        schema=_FINAL_SCHEMA if use_schema else None,
    )
    validate_group_decisions(checks, response.get("checks"))
    if (response.get("verdict") not in ("pass", "reject", "uncertain")
            or response.get("semantic_equivalence") not in (
                "equivalent", "different", "uncertain")
            or response.get("naturalness") not in (
                "improved", "not_improved", "uncertain")
            or not isinstance(response.get("issues"), list)
            or any(not isinstance(i, str) for i in response["issues"])
            or len(response["issues"]) > 8
            or not isinstance(response.get("explanation"), str)):
        raise ReviewFormatError("final_judge_schema_invalid")
    result = {key: response[key] for key in (
        "verdict", "semantic_equivalence", "naturalness",
        "issues", "explanation", "checks",
    )}
    result["issues"] = list(result["issues"])
    if check_failures(result["checks"]) and result["verdict"] == "pass":
        result["verdict"] = "uncertain"
        result["semantic_equivalence"] = "uncertain"
        result["issues"].append("At least one risk group was not preserved.")
    return result


def passing_judgment(judgment: Mapping[str, Any]) -> bool:
    return (
        judgment.get("verdict") == "pass"
        and judgment.get("semantic_equivalence") == "equivalent"
        and judgment.get("naturalness") == "improved"
        and judgment.get("issues") == []
        and isinstance(judgment.get("checks"), list)
        and bool(judgment["checks"])
        and not check_failures(judgment["checks"])
    )


def rejection_reason(judgment: Mapping[str, Any]) -> str:
    if (judgment.get("verdict") == "uncertain"
            or judgment.get("semantic_equivalence") == "uncertain"):
        return "rejected_uncertain"
    if judgment.get("semantic_equivalence") == "different":
        return "rejected_semantic"
    if judgment.get("naturalness") != "improved":
        return "rejected_quality"
    return "rejected_validation_error"


