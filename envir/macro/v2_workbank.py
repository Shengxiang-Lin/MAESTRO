"""Work-product grammar for macro orchestration, independent of tool steps.

A Recipe consumes *complete findings* from earlier work and produces one
complete deliverable. Its internal_actions are private Sub-Agent execution
hints, not Main-Agent delegations. Multiple producers per artifact type
create alternate semantic decomposition routes, not arbitrary graph shapes.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Recipe:
    name: str
    work_type: str
    output: str
    inputs: tuple[tuple[str, str, str], ...]
    goal: str
    deliverable: str
    capabilities: tuple[str, ...]
    internal_actions: tuple[str, ...]
    source_role: str = ""

    def input_schema(self) -> dict[str, str]:
        return {slot: typ for slot, typ, _reason in self.inputs}


