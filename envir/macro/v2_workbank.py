BY_OUTPUT: dict[str, tuple[Recipe, ...]] = {
    output: tuple(r for r in RECIPES if r.output == output)
    for output in OUTPUT_FIELDS
}

if any(not options for options in BY_OUTPUT.values()):
    raise RuntimeError("work grammar has a required artifact type with no producer")
if any(
    input_type not in BY_OUTPUT or not why
    for recipe in RECIPES
    for _slot, input_type, why in recipe.inputs
):
    raise RuntimeError("work grammar contains an invalid/unexplained dependency")

